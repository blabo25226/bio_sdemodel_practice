"""Day 5: Zhang et al. (2025) END-nSDE, circadian clock -> SINDy distillation.

Pipeline (all settings frozen in ``configs/daily_neural_sde_day05.json``):

1. Take the paper's minimal circadian SDE, Eq. (9), as the ground truth:
   d x_t = (-alpha x_t - beta y_t) dt + sigma0 dB1_t + sigma0 c dB2_t,
   d y_t = (beta x_t - alpha y_t) dt + sigma0 c dB1_t + sigma0 dB2_t,
   with (alpha, beta) = (0.19, 0.21) (paper Section 3.1), initial
   condition (x(0), y(0)) = (0, 1), and the constant-diffusion form
   Eq. (11) at the single slice (sigma0, c) = (0.20, 0.50) of the
   paper's 25-combination grid. The paper's END-nSDE takes the state
   and (sigma0, c) as inputs and reconstructs a family of SDEs; here
   the extrinsic-noise family dimension is cut (declared deviation):
   the teacher does NOT take (sigma0, c) as inputs, and nothing is
   claimed about generalization across (sigma0, c). Trajectories are
   regenerated by Euler-Maruyama at dt = 0.001 and observed every
   0.05 on [0, 4] (81 points); the horizon is extended from the
   printed [0, 1] as a declared deviation (see the config).
2. Fit two generic MLP neural SDEs: vEM (plain Euler transition
   likelihood, freezing f and Sigma over dt_obs = 0.05) and vW2
   (simulation-based, temporally-decoupled W2 objective: per
   observation time, per-dimension sorted-marginal squared W2 plus
   0.5 * ||Cov_sim - Cov_train||_F^2 -- an approximation of the
   paper's joint W2 loss, declared in the config). The distilled
   teacher is vW2, fixed a priori because the paper's method is
   W2-based. The estimator comparison (H5) is judged on the W2
   distribution metric and on Sigma NRMSE with a pre-declared tie
   zone of 0.01, never on drift NRMSE alone (Day 4 reflection:
   drift is weakly identified at dt_obs = 0.05).
3. Distill the vW2 teacher into polynomial SINDy models in (x, y)
   by direct function queries on trajectory-disjoint splits, in the
   conventions of ``src/distill.py`` (validation-only selection,
   test once). A collinearity diagnostic on train query states
   precedes fitting (Day 1 reflection), and an off-manifold grid
   diagnostic is standard (Day 2 reflection; the grid overlaps the
   marginal data range, so it is not claimed as strong extrapolation
   -- Day 3 reflection).
4. Validate by paired simulation with the full diffusion matrix
   and shared Brownian increments, retaining failed-trajectory
   mass and counting radius excursions (> 2.0, twice the initial
   radius) as a domain-validity measure separate from failure
   (Day 4 reflection). Paper-axis proxy (H6): terminal-time mean
   radius under teacher vs symbolic, with the paired standard
   error reported (Day 4 reflection).

Run from the repository root:  ``python -m src.daily_neural_sde.day05_zhang_circadian``
Outputs land in ``outputs/daily_neural_sde/day05/``.
"""
