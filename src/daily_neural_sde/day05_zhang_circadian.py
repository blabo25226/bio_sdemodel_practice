# ---------------------------------------------------------------- truth

def _params(cfg: dict) -> dict[str, float]:
    gt = cfg["ground_truth_sde"]
    return {"alpha": float(gt["alpha"]), "beta": float(gt["beta"]),
            "sigma0": float(gt["sigma0"]), "c": float(gt["c"])}


def true_drift(x: np.ndarray, cfg: dict) -> np.ndarray:
    """Ground-truth drift (-alpha x - beta y, beta x - alpha y)."""
    p = _params(cfg)
    x = np.atleast_2d(np.asarray(x, dtype=np.float64))
    return np.stack([-p["alpha"] * x[:, 0] - p["beta"] * x[:, 1],
                     p["beta"] * x[:, 0] - p["alpha"] * x[:, 1]], axis=1)


def true_L(x: np.ndarray, cfg: dict) -> np.ndarray:
    """Ground-truth constant diffusion matrix (n, 2, 2)."""
    p = _params(cfg)
    x = np.atleast_2d(np.asarray(x, dtype=np.float64))
    L = np.zeros((len(x), 2, 2))
    L[:, 0, 0] = p["sigma0"]
    L[:, 0, 1] = p["sigma0"] * p["c"]
    L[:, 1, 0] = p["sigma0"] * p["c"]
    L[:, 1, 1] = p["sigma0"]
    return L


def true_L_entries(x: np.ndarray, cfg: dict) -> np.ndarray:
    """Cholesky entries in (L11, L12, L21, L22) order -> (n, 4).

    NOTE: the truth diffusion matrix here is symmetric, not
    triangular. The (L11, L12, L21, L22) entries are reported as a
    matrix, and the teacher's triangular Cholesky factor is compared
    to it through Sigma = L L^T (the identified object) as well as
    through the raw entries; the Sigma clause is the one that
    identifies the diffusion.
    """
    L = true_L(x, cfg)
    return np.stack([L[:, 0, 0], L[:, 0, 1], L[:, 1, 0], L[:, 1, 1]], axis=1)


def sigma_from_L(L: np.ndarray) -> np.ndarray:
    """Sigma = L L^T for matrices (n, 2, 2) -> (n, 2, 2)."""
    return np.einsum("nij,nkj->nik", L, L)


def L_from_entries(entries: np.ndarray) -> np.ndarray:
    """(n, 4) entries in (L11, L12, L21, L22) order -> (n, 2, 2)."""
    e = np.atleast_2d(np.asarray(entries, dtype=np.float64))
    L = np.zeros((len(e), 2, 2))
    L[:, 0, 0], L[:, 0, 1], L[:, 1, 0], L[:, 1, 1] = e[:, 0], e[:, 1], e[:, 2], e[:, 3]
    return L


def true_sigma_matrix(cfg: dict) -> np.ndarray:
    """Constant ground-truth Sigma = L L^T (2, 2)."""
    p = _params(cfg)
    s2 = p["sigma0"] ** 2
    return s2 * np.array([[1.0 + p["c"] ** 2, 2.0 * p["c"]],
                          [2.0 * p["c"], 1.0 + p["c"] ** 2]])


def generate_data(cfg: dict) -> np.ndarray:
    """Euler-Maruyama simulation -> (n_traj, 81, 2) in (x, y)."""
    p = _params(cfg)
    data_cfg = cfg["data"]
    rng = np.random.default_rng(cfg["seed"])
    n_traj = data_cfg["n_trajectories"]
    dt_fine = data_cfg["dt_fine"]
    n_fine = int(round(data_cfg["t_end"] / dt_fine))
    n_obs = int(round(data_cfg["t_end"] / data_cfg["dt_obs"]))
    obs_every = int(round(data_cfg["dt_obs"] / dt_fine))
    x = np.zeros(n_traj)
    y = np.full(n_traj, cfg["ground_truth_sde"]["x0"][1])
    trajectories = np.empty((n_traj, n_obs + 1, 2))
    trajectories[:, 0, 0] = x
    trajectories[:, 0, 1] = y
    sqrt_dt = np.sqrt(dt_fine)
    for step in range(1, n_fine + 1):
        z1 = rng.standard_normal(n_traj)
        z2 = rng.standard_normal(n_traj)
        x_new = x + (-p["alpha"] * x - p["beta"] * y) * dt_fine \
            + p["sigma0"] * sqrt_dt * z1 + p["sigma0"] * p["c"] * sqrt_dt * z2
        y_new = y + (p["beta"] * x - p["alpha"] * y) * dt_fine \
            + p["sigma0"] * p["c"] * sqrt_dt * z1 + p["sigma0"] * sqrt_dt * z2
        x, y = x_new, y_new
        if step % obs_every == 0:
            trajectories[:, step // obs_every, 0] = x
            trajectories[:, step // obs_every, 1] = y
    return trajectories


def split_indices(cfg: dict) -> dict[str, np.ndarray]:
    """Trajectory-disjoint train / validation / test split (seeded)."""
    rng = np.random.default_rng(cfg["split"]["seed"])
    n = cfg["data"]["n_trajectories"]
    perm = rng.permutation(n)
    n_train = cfg["split"]["train"]
    n_val = cfg["split"]["validation"]
    return {"train": perm[:n_train],
            "validation": perm[n_train:n_train + n_val],
            "test": perm[n_train + n_val:]}


def query_states(trajectories: np.ndarray, idx: np.ndarray) -> np.ndarray:
    """All observed states for the given trajectories -> (n, 2)."""
    return trajectories[idx].reshape(-1, 2)


def transitions(trajectories: np.ndarray, idx: np.ndarray) -> tuple[np.ndarray, np.ndarray]:
    """One-step observed transitions (start, end) for given trajectories."""
    block = trajectories[idx]
    return block[:, :-1].reshape(-1, 2), block[:, 1:].reshape(-1, 2)


# ------------------------------------------------------------- MLP teacher

class _MLPTeacher:
    """Drift MLP + Cholesky-diffusion MLP (torch).

    Inputs are standardized with the train-query mean/std passed in.
    Diffusion outputs: raw (L11, L21, L22) mapped to
    L11 = softplus + 0.01, L21 free, L22 = softplus + 0.01, L12 = 0.
    ``dtype`` selects float64 (EM teacher) or float32 (W2 teacher).
    """

    def __init__(self, mean: np.ndarray, scale: np.ndarray, seed: int, dtype):
        import torch
        torch.manual_seed(seed)
        self.torch = torch
        self.dtype = dtype
        self.mean = torch.as_tensor(mean, dtype=dtype)
        self.scale = torch.as_tensor(scale, dtype=dtype)
        hidden = [32, 32]

        def mlp(out_dim: int):
            return torch.nn.Sequential(
                torch.nn.Linear(2, hidden[0], dtype=dtype), torch.nn.Tanh(),
                torch.nn.Linear(hidden[0], hidden[1], dtype=dtype), torch.nn.Tanh(),
                torch.nn.Linear(hidden[1], out_dim, dtype=dtype))

        self.drift_net = mlp(2)
        self.diff_net = mlp(3)
        self.params = list(self.drift_net.parameters()) + list(self.diff_net.parameters())

    def _standardize(self, x_t):
        return (x_t - self.mean) / self.scale

    def drift(self, x_t):
        return self.drift_net(self._standardize(x_t))

    def L(self, x_t):
        torch = self.torch
        raw = self.diff_net(self._standardize(x_t))
        n = len(x_t)
        L = torch.zeros((n, 2, 2), dtype=self.dtype)
        L[:, 0, 0] = torch.nn.functional.softplus(raw[:, 0]) + 0.01
        L[:, 1, 0] = raw[:, 1]
        L[:, 1, 1] = torch.nn.functional.softplus(raw[:, 2]) + 0.01
        return L


def _state_dict(model: _MLPTeacher) -> dict[str, Any]:
    import torch
    state = {}
    for name, net in [("drift", model.drift_net), ("diff", model.diff_net)]:
        for i, layer in enumerate(net):
            if isinstance(layer, torch.nn.Linear):
                state[f"{name}.{i}.weight"] = layer.weight
                state[f"{name}.{i}.bias"] = layer.bias
    return state


def _load_state(model: _MLPTeacher, state: dict[str, np.ndarray]) -> None:
    import torch
    for name, net in [("drift", model.drift_net), ("diff", model.diff_net)]:
        for i, layer in enumerate(net):
            if isinstance(layer, torch.nn.Linear):
                layer.weight.data = torch.as_tensor(state[f"{name}.{i}.weight"],
                                                    dtype=model.dtype)
                layer.bias.data = torch.as_tensor(state[f"{name}.{i}.bias"],
                                                  dtype=model.dtype)


def _np_state(model: _MLPTeacher) -> dict[str, np.ndarray]:
    return {k: v.detach().numpy().copy() for k, v in _state_dict(model).items()}


def teacher_drift_np(model: _MLPTeacher, x: np.ndarray) -> np.ndarray:
    """MLP teacher drift evaluated in numpy."""
    import torch
    x_t = torch.as_tensor(np.atleast_2d(x), dtype=model.dtype)
    with torch.no_grad():
        return model.drift(x_t).numpy().astype(np.float64)


def teacher_L_np(model: _MLPTeacher, x: np.ndarray) -> np.ndarray:
    """MLP teacher Cholesky matrix evaluated in numpy -> (n, 2, 2)."""
    import torch
    x_t = torch.as_tensor(np.atleast_2d(x), dtype=model.dtype)
    with torch.no_grad():
        return model.L(x_t).numpy().astype(np.float64)


def teacher_L_entries_np(model: _MLPTeacher, x: np.ndarray) -> np.ndarray:
    """Teacher Cholesky entries in (L11, L12, L21, L22) order."""
    L = teacher_L_np(model, x)
    return np.stack([L[:, 0, 0], L[:, 0, 1], L[:, 1, 0], L[:, 1, 1]], axis=1)


def _transition_nll_em(model: _MLPTeacher, x0: np.ndarray, x1: np.ndarray, dt: float):
    """Plain Euler Gaussian transition NLL (torch, float64)."""
    import torch
    x0_t = torch.as_tensor(x0, dtype=torch.float64)
    x1_t = torch.as_tensor(x1, dtype=torch.float64)
    mean = x0_t + model.drift(x0_t) * dt
    L = model.L(x0_t)
    cov = torch.einsum("nij,nkj->nik", L, L) * dt \
        + 1e-12 * torch.eye(2, dtype=torch.float64)[None]
    diff = (x1_t - mean)[:, :, None]
    sign, logdet = torch.linalg.slogdet(cov)
    if bool((sign <= 0).any()):
        raise ValueError("non-positive-definite transition covariance")
    quad = torch.einsum("nij,njk,nk->n",
                        diff.transpose(1, 2), torch.linalg.inv(cov), diff[:, :, 0])
    return torch.mean(0.5 * (logdet + quad + 2.0 * np.log(2.0 * np.pi)))


def train_em_teacher(train_tr: tuple, val_tr: tuple, cfg: dict,
                     mean: np.ndarray, scale: np.ndarray) -> dict[str, Any]:
    """Fit the EM likelihood teacher; checkpoint on val NLL."""
    import torch
    model = _MLPTeacher(mean, scale, seed=123, dtype=torch.float64)
    dt = cfg["data"]["dt_obs"]
    # Subsample transitions for CPU-scale full-batch training (seeded).
    rng = np.random.default_rng(1)
    x0_tr, x1_tr = train_tr
    sub = rng.permutation(len(x0_tr))[:40000]
    x0_sub, x1_sub = x0_tr[sub], x1_tr[sub]
    opt = torch.optim.Adam(model.params, lr=cfg["teacher"]["lr_em"])
    epochs, every = 120, 10
    best = {"nll": float("inf"), "state": None}
    for epoch in range(epochs):
        opt.zero_grad()
        loss = _transition_nll_em(model, x0_sub, x1_sub, dt)
        loss.backward()
        opt.step()
        if epoch % every == 0 or epoch == epochs - 1:
            with torch.no_grad():
                val_nll = float(_transition_nll_em(model, val_tr[0], val_tr[1], dt))
            if val_nll < best["nll"]:
                best = {"nll": val_nll, "state": _np_state(model)}
    _load_state(model, best["state"])
    return {"val_nll": best["nll"], "model": model, "state": best["state"]}


def _simulate_teacher_torch(model: _MLPTeacher, n_paths: int, n_steps: int,
                            dt: float, increments) -> Any:
    """Differentiable Euler simulation from (0, 1) -> (n_paths, n_steps+1, 2)."""
    torch = model.torch
    x = torch.zeros((n_paths, 2), dtype=model.dtype)
    x[:, 1] = 1.0
    path = [x]
    sqrt_dt = float(np.sqrt(dt))
    for step in range(n_steps):
        drift = model.drift(x)
        L = model.L(x)
        x = x + drift * dt + torch.einsum("nij,nj->ni", L, increments[:, step]) * sqrt_dt
        path.append(x)
    return torch.stack(path, dim=1)


def _w2_loss_torch(model: _MLPTeacher, target: Any, dt_sim: float,
                   obs_every: int, increments) -> Any:
    """Temporally-decoupled marginal-W2 + covariance loss (torch).

    ``target`` is (n_paths, n_obs, 2) of reference trajectories.
    At each observation time: sum over dimensions of the
    sorted-marginal squared W2 distance plus 0.5 * ||Cov_sim -
    Cov_target||_F^2. The mean over observation times is returned.
    """
    torch = model.torch
    n_paths = target.shape[0]
    n_steps = int(round(cfg_global["data"]["t_end"] / dt_sim))
    sim = _simulate_teacher_torch(model, n_paths, n_steps, dt_sim, increments)
    sim_obs = sim[:, ::obs_every]
    losses = []
    for t in range(sim_obs.shape[1]):
        s = sim_obs[:, t]
        g = target[:, t]
        s_sorted, _ = torch.sort(s, dim=0)
        g_sorted, _ = torch.sort(g, dim=0)
        marginal = torch.mean((s_sorted - g_sorted) ** 2)
        s_c = s - s.mean(dim=0, keepdim=True)
        g_c = g - g.mean(dim=0, keepdim=True)
        cov_s = (s_c.T @ s_c) / max(n_paths - 1, 1)
        cov_g = (g_c.T @ g_c) / max(n_paths - 1, 1)
        cov_term = 0.5 * torch.sum((cov_s - cov_g) ** 2)
        losses.append(marginal + cov_term)
    return torch.stack(losses).mean()


cfg_global: dict = {}


def train_w2_teacher(train_traj: np.ndarray, val_traj: np.ndarray,
                     cfg: dict, mean: np.ndarray, scale: np.ndarray) -> dict[str, Any]:
    """Fit the W2 simulation-based teacher; checkpoint on val W2 loss."""
    import torch
    model = _MLPTeacher(mean, scale, seed=456, dtype=torch.float32)
    dt_sim = cfg["teacher"]["w2_sim_dt"]
    dt_obs = cfg["data"]["dt_obs"]
    obs_every = int(round(dt_obs / dt_sim))
    n_steps = int(round(cfg["data"]["t_end"] / dt_sim))
    batch = cfg["teacher"]["w2_batch_paths"]
    opt = torch.optim.Adam(model.params, lr=cfg["teacher"]["lr_w2"])
    epochs = cfg["teacher"]["w2_epochs"]
    rng = np.random.default_rng(2)
    val_t = torch.as_tensor(val_traj[:batch], dtype=torch.float32)
    best = {"loss": float("inf"), "state": None}
    for epoch in range(epochs):
        idx = rng.choice(len(train_traj), size=batch, replace=False)
        target = torch.as_tensor(train_traj[idx], dtype=torch.float32)
        increments = torch.randn((batch, n_steps, 2), dtype=torch.float32)
        opt.zero_grad()
        loss = _w2_loss_torch(model, target, dt_sim, obs_every, increments)
        loss.backward()
        opt.step()
        if epoch % 20 == 0 or epoch == epochs - 1:
            with torch.no_grad():
                inc_val = torch.randn((batch, n_steps, 2), dtype=torch.float32)
                val_loss = float(_w2_loss_torch(model, val_t, dt_sim, obs_every, inc_val))
            if val_loss < best["loss"]:
                best = {"loss": val_loss, "state": _np_state(model)}
            print(f"[w2] epoch {epoch} train loss={float(loss.detach()):.5f} "
                  f"val loss={val_loss:.5f}", flush=True)
    _load_state(model, best["state"])
    return {"val_w2_loss": best["loss"], "model": model, "state": best["state"]}


def w2_loss_np(sim_traj: np.ndarray, target_traj: np.ndarray) -> float:
    """Numpy version of the temporally-decoupled marginal-W2 + covariance loss."""
    losses = []
    for t in range(sim_traj.shape[1]):
        s, g = sim_traj[:, t], target_traj[:, t]
        marginal = float(np.mean((np.sort(s, axis=0) - np.sort(g, axis=0)) ** 2))
        cov_term = 0.5 * float(np.sum((np.cov(s.T) - np.cov(g.T)) ** 2))
        losses.append(marginal + cov_term)
    return float(np.mean(losses))


def simulate_matrix(drift_fn, L_fn, x0: np.ndarray, dt: float, n_steps: int,
                    increments: np.ndarray, failure_radius: float,
                    domain_radius: float) -> dict[str, Any]:
    """Paired Euler simulation with a full 2x2 diffusion matrix.

    Failures latch (non-finite / outside ``failure_radius``); radius
    excursions above ``domain_radius`` are counted separately as a
    domain-validity measure, not as failures.
    """
    x = np.array(x0, dtype=np.float64, copy=True)
    n, d = x.shape
    if increments.shape != (n, n_steps, d):
        raise ValueError("increments shape mismatch")
    failed = np.zeros(n, dtype=bool)
    failure_class: list[str | None] = [None] * n
    ever_excursion = np.zeros(n, dtype=bool)
    sqrt_dt = np.sqrt(dt)
    for step in range(n_steps):
        active = ~failed
        if active.any():
            drift = drift_fn(x[active])
            L = L_fn(x[active])
            x[active] = x[active] + drift * dt \
                + np.einsum("nij,nj->ni", L, increments[active, step]) * sqrt_dt
        ever_excursion = ever_excursion | ((np.linalg.norm(x, axis=1) > domain_radius) & ~failed)
        bad_nonfinite = ~np.isfinite(x).all(axis=1)
        bad_radius = np.linalg.norm(x, axis=1) > failure_radius
        newly = (~failed) & (bad_nonfinite | bad_radius)
        for idx in np.flatnonzero(newly):
            failure_class[idx] = "non_finite" if bad_nonfinite[idx] else "outside_radius"
        failed = failed | newly
        x[failed] = np.nan
    return {"terminal": x, "failed": failed, "failure_class": failure_class,
            "failure_rate": float(np.mean(failed)),
            "domain_excursion_rate": float(np.mean(ever_excursion))}


def main() -> dict[str, Any]:
    """Run the Day 5 pipeline and write outputs + results.json."""
    global cfg_global
    cfg = json.loads(CONFIG_PATH.read_text())
    cfg_global = cfg
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    trajectories = generate_data(cfg)
    splits = split_indices(cfg)
    dt_obs = cfg["data"]["dt_obs"]
    n_obs = trajectories.shape[1]
    data_stats = {
        "x_mean": float(np.mean(trajectories[:, :, 0])),
        "x_std": float(np.std(trajectories[:, :, 0])),
        "x_range": [float(np.min(trajectories[:, :, 0])),
                    float(np.max(trajectories[:, :, 0]))],
        "y_mean": float(np.mean(trajectories[:, :, 1])),
        "y_std": float(np.std(trajectories[:, :, 1])),
        "y_range": [float(np.min(trajectories[:, :, 1])),
                    float(np.max(trajectories[:, :, 1]))],
        "terminal_radius_mean": float(np.mean(np.linalg.norm(trajectories[:, -1], axis=1))),
        "terminal_radius_std": float(np.std(np.linalg.norm(trajectories[:, -1], axis=1))),
    }
    print("data:", data_stats, flush=True)

    # --- collinearity diagnostic on train query states (before fitting)
    train_q = query_states(trajectories, splits["train"])
    corr_xy = float(np.corrcoef(train_q[:, 0], train_q[:, 1])[0, 1])
    vif = float(1.0 / max(1.0 - corr_xy ** 2, 1e-12))
    powers2 = monomial_powers(2, 2)
    deg2_all = evaluate_powers(train_q, powers2)
    keep = np.any(powers2 != 0, axis=1)
    deg2 = deg2_all[:, keep]
    corr_mat = np.corrcoef(deg2.T)
    iu = np.triu_indices(len(corr_mat), k=1)
    max_deg2_corr = float(np.nanmax(np.abs(corr_mat[iu])))
    collinearity = {"corr_x_y_train": corr_xy, "vif_x_y_train": vif,
                    "max_pairwise_abs_corr_degree2_features_train": max_deg2_corr}
    print("collinearity:", collinearity, flush=True)

    # --- MLP teachers (vEM likelihood / vW2 simulation-based)
    std_mean = train_q.mean(axis=0)
    std_scale = train_q.std(axis=0)
    std_scale[std_scale < 1e-12] = 1.0
    train_tr = transitions(trajectories, splits["train"])
    val_tr = transitions(trajectories, splits["validation"])
    test_tr = transitions(trajectories, splits["test"])
    em = train_em_teacher(train_tr, val_tr, cfg, std_mean, std_scale)
    print(f"[em] val NLL={em['val_nll']:.5f}", flush=True)
    w2 = train_w2_teacher(trajectories[splits["train"]],
                          trajectories[splits["validation"]],
                          cfg, std_mean, std_scale)
    print(f"[w2] val W2 loss={w2['val_w2_loss']:.5f}", flush=True)
    fitted_models = {"em": em["model"], "w2": w2["model"]}
    teacher = fitted_models["w2"]

    # --- estimator comparison on test query states, split by regime
    queries = {split: query_states(trajectories, splits[split])
               for split in ["train", "validation", "test"]}
    # Time index of each flattened query state (trajectory-major order).
    time_idx = np.tile(np.arange(n_obs), len(splits["test"]))
    radius_q = np.linalg.norm(queries["test"], axis=1)
    estimators: dict[str, Any] = {}
    for name, model in fitted_models.items():
        pred_drift = teacher_drift_np(model, queries["test"])
        pred_L = teacher_L_np(model, queries["test"])
        pred_sigma = sigma_from_L(pred_L).reshape(len(pred_L), -1)
        truth_sigma = np.tile(true_sigma_matrix(cfg).reshape(-1), (len(pred_L), 1))
        entry: dict[str, Any] = {
            "drift_nrmse_vs_truth_test": nrmse(true_drift(queries["test"], cfg), pred_drift),
            "drift_rms_error_vs_truth_test": float(
                np.sqrt(np.mean((pred_drift - true_drift(queries["test"], cfg)) ** 2))),
            "sigma_nrmse_vs_truth_test": nrmse(truth_sigma, pred_sigma),
            "sigma_rms_error_vs_truth_test": float(
                np.sqrt(np.mean((pred_sigma - truth_sigma) ** 2)))}
        for regime, mask in [
                ("radius_lt_0.5", radius_q < 0.5),
                ("radius_ge_0.5", radius_q >= 0.5),
                ("early_t_lt_1", time_idx * dt_obs < 1.0),
                ("late_t_ge_2", time_idx * dt_obs >= 2.0)]:
            entry[f"drift_nrmse_vs_truth_test_{regime}"] = nrmse(
                true_drift(queries["test"][mask], cfg), pred_drift[mask])
            entry[f"sigma_nrmse_vs_truth_test_{regime}"] = nrmse(
                truth_sigma[mask], pred_sigma[mask])
            entry[f"n_{regime}"] = int(mask.sum())
        estimators[name] = entry
        print(f"[{name}] drift NRMSE={entry['drift_nrmse_vs_truth_test']:.4f} "
              f"Sigma NRMSE={entry['sigma_nrmse_vs_truth_test']:.4f}", flush=True)
    estimators["em"]["val_nll"] = em["val_nll"]
    estimators["w2"]["val_w2_loss"] = w2["val_w2_loss"]

    # Test-set W2 distribution loss for both teachers (simulated from (0, 1)).
    sim_cfg = cfg["simulation"]
    rng_w2 = np.random.default_rng(99)
    n_test = len(splits["test"])
    n_steps = int(round(sim_cfg["t_end"] / sim_cfg["dt"]))
    test_traj = trajectories[splits["test"]]
    w2_losses = {}
    for name, model in fitted_models.items():
        inc = rng_w2.standard_normal((n_test, n_steps, 2))
        sim = simulate_matrix(lambda x, m=model: teacher_drift_np(m, x),
                              lambda x, m=model: teacher_L_np(m, x),
                              np.tile(np.array([0.0, 1.0]), (n_test, 1)),
                              sim_cfg["dt"], n_steps, inc,
                              sim_cfg["failure_radius"], sim_cfg["domain_excursion_radius"])
        # Rebuild full observed paths at dt_obs for the W2 loss: simulate
        # again keeping every 5th step.
        x = np.tile(np.array([0.0, 1.0]), (n_test, 1)).astype(np.float64)
        path = [x.copy()]
        sqrt_dt = np.sqrt(sim_cfg["dt"])
        for step in range(n_steps):
            drift = teacher_drift_np(model, x)
            L = teacher_L_np(model, x)
            x = x + drift * sim_cfg["dt"] \
                + np.einsum("nij,nj->ni", L, inc[:, step]) * sqrt_dt
            if (step + 1) % 5 == 0:
                path.append(x.copy())
        sim_obs = np.stack(path, axis=1)
        w2_losses[name] = w2_loss_np(sim_obs, test_traj)
        estimators[name]["test_w2_loss"] = w2_losses[name]
        print(f"[{name}] test W2 loss={w2_losses[name]:.5f}", flush=True)
    _ = sim  # terminal-only sim above is superseded by the path sim

    # --- polynomial SINDy distillation of the W2 teacher
    teacher_drift_q = {s: teacher_drift_np(teacher, queries[s]) for s in queries}
    teacher_L_q = {s: teacher_L_entries_np(teacher, queries[s]) for s in queries}
    truth_drift_q = {s: true_drift(queries[s], cfg) for s in queries}
    truth_L_q = {s: true_L_entries(queries[s], cfg) for s in queries}
    distilled: dict[str, Any] = {}
    models: dict[str, PolynomialField] = {}
    expanded_fields: dict[str, Any] = {}
    for field, degrees, targets in [
            ("drift", cfg["distillation"]["drift_degrees"], teacher_drift_q),
            ("diffusion", cfg["distillation"]["diffusion_degrees"], teacher_L_q)]:
        best_field = None
        for degree in degrees:
            for threshold in cfg["distillation"]["thresholds"]:
                model = fit_polynomial_field(
                    queries["train"], targets["train"], degree, threshold,
                    ridge=cfg["distillation"]["ridge"])
                val_err = nrmse(targets["validation"],
                                model.predict(queries["validation"]))
                if best_field is None or val_err < best_field["val_nrmse"]:
                    best_field = {"model": model, "degree": degree,
                                  "threshold": threshold, "val_nrmse": val_err}
        model = best_field["model"]
        test_err = nrmse(targets["test"], model.predict(queries["test"]))
        truth_err = None
        if field == "drift":
            truth_err = nrmse(truth_drift_q["test"], model.predict(queries["test"]))
        expanded = expand_to_original(model)
        model.save(OUT_DIR / f"symbolic_{field}.json")
        models[field] = model
        expanded_fields[field] = expanded
        entry = {
            "degree": best_field["degree"], "threshold": best_field["threshold"],
            "active_terms": int(model.metadata["active_terms"]),
            "val_nrmse_vs_teacher": best_field["val_nrmse"],
            "test_nrmse_vs_teacher": test_err,
            "test_nrmse_vs_truth": truth_err,
            "expanded": [{str(k): v for k, v in poly.items()} for poly in expanded]}
        if field == "drift":
            # Linear-coefficient clause (H3): expanded constant + linear
            # coefficients vs the truth (0, [[-alpha, -beta], [beta, -alpha]]).
            p = _params(cfg)
            truth_lin = np.array([[0.0, -p["alpha"], -p["beta"]],
                                  [0.0, p["beta"], -p["alpha"]]])
            sym_lin = np.zeros((2, 3))
            for i, poly in enumerate(expanded):
                sym_lin[i, 0] = poly.get((0, 0), 0.0)
                sym_lin[i, 1] = poly.get((1, 0), 0.0)
                sym_lin[i, 2] = poly.get((0, 1), 0.0)
            entry["linear_coefficients"] = sym_lin.tolist()
            entry["linear_coefficient_rmse_vs_truth"] = float(
                np.sqrt(np.mean((sym_lin - truth_lin) ** 2)))
            entry["linear_coefficient_truth"] = truth_lin.tolist()
        if field == "diffusion":
            pred = model.predict(queries["test"])
            entry["per_entry_test_rms_error"] = [
                float(np.sqrt(np.mean((pred[:, j] - targets["test"][:, j]) ** 2)))
                for j in range(4)]
            entry["per_entry_test_rms_target"] = [
                float(np.sqrt(np.mean(targets["test"][:, j] ** 2)))
                for j in range(4)]
            entry["sigma_test_nrmse_vs_teacher"] = nrmse(
                sigma_from_L(L_from_entries(targets["test"])).reshape(len(pred), -1),
                sigma_from_L(L_from_entries(pred)).reshape(len(pred), -1))
            entry["sigma_test_nrmse_vs_truth"] = nrmse(
                np.tile(true_sigma_matrix(cfg).reshape(-1), (len(pred), 1)),
                sigma_from_L(L_from_entries(pred)).reshape(len(pred), -1))
        distilled[field] = entry
        print(f"[{field}] degree={best_field['degree']} thr={best_field['threshold']} "
              f"test NRMSE vs teacher={test_err:.5f} truth={truth_err}", flush=True)

    # oracle diagnostic: same SINDy procedure on ground-truth fields
    oracle = {}
    for field, degrees, targets in [
            ("drift", cfg["distillation"]["drift_degrees"], truth_drift_q),
            ("diffusion", cfg["distillation"]["diffusion_degrees"], truth_L_q)]:
        best_o = None
        for degree in degrees:
            for threshold in cfg["distillation"]["thresholds"]:
                model = fit_polynomial_field(
                    queries["train"], targets["train"], degree, threshold,
                    ridge=cfg["distillation"]["ridge"])
                val_err = nrmse(targets["validation"],
                                model.predict(queries["validation"]))
                if best_o is None or val_err < best_o[0]:
                    best_o = (val_err, degree, threshold, model)
        oracle[field] = {"degree": best_o[1], "threshold": best_o[2],
                         "test_nrmse_vs_truth": nrmse(
                             targets["test"], best_o[3].predict(queries["test"]))}

    # --- off-manifold grid (Day 2 reflection: standard procedure)
    grid = np.array([[a, b] for a in [-1.0, -0.5, 0.0, 0.5, 1.0]
                     for b in [-1.0, -0.5, 0.0, 0.5, 1.0]])
    off = {
        "drift_nrmse_symbolic_vs_teacher": nrmse(
            teacher_drift_np(teacher, grid), models["drift"].predict(grid)),
        "drift_nrmse_symbolic_vs_truth": nrmse(
            true_drift(grid, cfg), models["drift"].predict(grid)),
        "drift_nrmse_teacher_vs_truth": nrmse(
            true_drift(grid, cfg), teacher_drift_np(teacher, grid)),
        "diffusion_nrmse_symbolic_vs_teacher": nrmse(
            teacher_L_entries_np(teacher, grid), models["diffusion"].predict(grid)),
        "diffusion_nrmse_symbolic_vs_truth": nrmse(
            true_L_entries(grid, cfg), models["diffusion"].predict(grid)),
        "diffusion_nrmse_teacher_vs_truth": nrmse(
            true_L_entries(grid, cfg), teacher_L_entries_np(teacher, grid))}

    # --- paired simulation validation (full diffusion matrix)
    rng = np.random.default_rng(sim_cfg["seed"])
    increments = rng.standard_normal((n_test, n_steps, 2))
    x0 = trajectories[splits["test"], 0]
    sims = {}
    for name, drift_fn, L_fn in [
            ("neural", lambda x: teacher_drift_np(teacher, x),
             lambda x: teacher_L_np(teacher, x)),
            ("symbolic", lambda x: models["drift"].predict(x),
             lambda x: L_from_entries(models["diffusion"].predict(x))),
            ("truth", lambda x: true_drift(x, cfg),
             lambda x: true_L(x, cfg))]:
        sims[name] = simulate_matrix(drift_fn, L_fn, x0, sim_cfg["dt"],
                                     n_steps, increments,
                                     sim_cfg["failure_radius"],
                                     sim_cfg["domain_excursion_radius"])

    def paired_rmse(a_term, b_term):
        both_ok = ~(np.isnan(a_term).any(axis=1) | np.isnan(b_term).any(axis=1))
        diffs = a_term[both_ok] - b_term[both_ok]
        per_path = np.sqrt(np.mean(diffs ** 2, axis=1))
        return float(np.median(per_path)), int(both_ok.sum())

    sim_med, n_paired = paired_rmse(sims["symbolic"]["terminal"],
                                    sims["neural"]["terminal"])
    # H6 downstream: terminal mean radius, paired difference + paired SE.
    def radius_of(term):
        return np.linalg.norm(term, axis=1)

    both_ok = ~(np.isnan(sims["symbolic"]["terminal"]).any(axis=1)
                | np.isnan(sims["neural"]["terminal"]).any(axis=1))
    radius_diff = radius_of(sims["symbolic"]["terminal"])[both_ok] \
        - radius_of(sims["neural"]["terminal"])[both_ok]
    radius_paired = {
        "mean_radius_symbolic": float(np.mean(radius_of(sims["symbolic"]["terminal"])[both_ok])),
        "mean_radius_neural": float(np.mean(radius_of(sims["neural"]["terminal"])[both_ok])),
        "mean_radius_truth": float(np.mean(radius_of(sims["truth"]["terminal"])[
            ~(np.isnan(sims["truth"]["terminal"]).any(axis=1))])),
        "mean_diff_symbolic_minus_neural": float(np.mean(radius_diff)),
        "paired_se": float(np.std(radius_diff, ddof=1) / np.sqrt(len(radius_diff))),
        "n_paired": int(both_ok.sum())}
    simulation = {
        "failure_rate": {k: v["failure_rate"] for k, v in sims.items()},
        "failure_class_counts": {
            k: {cls: int(sum(1 for c in v["failure_class"] if c == cls))
                for cls in ["non_finite", "outside_radius"]}
            for k, v in sims.items()},
        "domain_excursion_rate": {k: v["domain_excursion_rate"] for k, v in sims.items()},
        "terminal_mean": {k: [float(v) for v in np.nanmean(
            sims[k]["terminal"], axis=0)] for k in sims},
        "terminal_std": {k: [float(v) for v in np.nanstd(
            sims[k]["terminal"], axis=0)] for k in sims},
        "paired_rmse_median_symbolic_vs_neural": sim_med,
        "n_paired": n_paired,
        "terminal_radius": radius_paired}

    # --- verdicts (frozen thresholds in the config)
    hyp = cfg["hypotheses"]
    sigma_diff = abs(estimators["w2"]["sigma_nrmse_vs_truth_test"]
                     - estimators["em"]["sigma_nrmse_vs_truth_test"])
    h5_sigma_ok = (estimators["w2"]["sigma_nrmse_vs_truth_test"]
                   <= estimators["em"]["sigma_nrmse_vs_truth_test"]
                   + hyp["H5_estimator_comparison_w2_vs_em"]["sigma_tie_zone"])
    h6_point = abs(radius_paired["mean_diff_symbolic_minus_neural"]) \
        <= hyp["H6_paper_axis_downstream"]["terminal_mean_radius_abs_diff_max"]
    h6_indeterminate = radius_paired["paired_se"] \
        >= hyp["H6_paper_axis_downstream"]["paired_se_indeterminate_threshold"]
    verdicts = {
        "H1_drift_distillation": bool(
            distilled["drift"]["test_nrmse_vs_teacher"]
            <= hyp["H1_drift_distillation"]["symbolic_drift_test_nrmse_vs_teacher_max"]),
        "H2_diffusion_distillation": bool(
            distilled["diffusion"]["test_nrmse_vs_teacher"]
            <= hyp["H2_diffusion_distillation"]["symbolic_diffusion_test_nrmse_vs_teacher_max"]
            and distilled["diffusion"]["sigma_test_nrmse_vs_teacher"]
            <= hyp["H2_diffusion_distillation"]["symbolic_sigma_test_nrmse_vs_teacher_max"]),
        "H3_truth_recovery": bool(
            distilled["drift"]["test_nrmse_vs_truth"]
            <= hyp["H3_truth_recovery"]["field_symbolic_drift_test_nrmse_vs_truth_max"]
            and distilled["drift"]["linear_coefficient_rmse_vs_truth"]
            <= hyp["H3_truth_recovery"]["linear_coefficient_rmse_max"]
            and estimators["w2"]["sigma_nrmse_vs_truth_test"]
            <= hyp["H3_truth_recovery"]["teacher_sigma_test_nrmse_vs_truth_max"]),
        "H4_simulation": bool(
            simulation["failure_rate"]["symbolic"]
            <= hyp["H4_simulation"]["symbolic_failure_rate_max"]
            and simulation["failure_rate"]["symbolic"]
            - simulation["failure_rate"]["neural"]
            <= hyp["H4_simulation"]["symbolic_failure_rate_minus_neural_max"]
            and sim_med <= hyp["H4_simulation"]["median_paired_rmse_vs_neural_max"]
            and simulation["domain_excursion_rate"]["symbolic"]
            - simulation["domain_excursion_rate"]["neural"]
            <= hyp["H4_simulation"]["domain_excursion_symbolic_minus_neural_max"]),
        "H5_estimator_comparison_w2_vs_em": bool(
            estimators["w2"]["test_w2_loss"] < estimators["em"]["test_w2_loss"]
            and h5_sigma_ok),
        "H6_paper_axis_downstream": bool(h6_point and not h6_indeterminate)}
    print("verdicts:", verdicts, flush=True)

    tex = tex_equations(expanded_fields["drift"],
                        ("\\hat f_x", "\\hat f_y"), VAR_NAMES) \
        + "\n" + tex_equations(expanded_fields["diffusion"],
                               ("\\hat L_{11}", "\\hat L_{12}",
                                "\\hat L_{21}", "\\hat L_{22}"), VAR_NAMES)
    (OUT_DIR / "symbolic_sde.tex").write_text(tex + "\n")

    results = {
        "data_stats": data_stats,
        "teacher_vs_truth_test": {
            "drift": estimators["w2"]["drift_nrmse_vs_truth_test"],
            "sigma": estimators["w2"]["sigma_nrmse_vs_truth_test"]},
        "symbolic_vs_teacher_test": {
            "drift": distilled["drift"]["test_nrmse_vs_teacher"],
            "diffusion": distilled["diffusion"]["test_nrmse_vs_teacher"],
            "sigma": distilled["diffusion"]["sigma_test_nrmse_vs_teacher"]},
        "symbolic_vs_truth_test": {
            "drift": distilled["drift"]["test_nrmse_vs_truth"],
            "sigma": distilled["diffusion"]["sigma_test_nrmse_vs_truth"]},
        "estimators": estimators,
        "sigma_nrmse_difference_w2_minus_em": float(
            estimators["w2"]["sigma_nrmse_vs_truth_test"]
            - estimators["em"]["sigma_nrmse_vs_truth_test"]),
        "sigma_diffusion_tie": bool(sigma_diff < 0.01),
        "distillation": distilled,
        "oracle": oracle,
        "collinearity": collinearity,
        "off_manifold_grid": off,
        "simulation": simulation,
        "h6_indeterminate_by_paired_se": bool(h6_indeterminate),
        "verdicts": verdicts}
    (OUT_DIR / "teacher_weights.json").write_text(json.dumps(
        {"mlp_teachers": {
            name: {"input_mean": std_mean.tolist(),
                   "input_scale": std_scale.tolist(),
                   "state": {k: v.tolist() for k, v in
                             _np_state(fitted_models[name]).items()}}
            for name in ["em", "w2"]},
         "em_val_nll": em["val_nll"],
         "w2_val_w2_loss": w2["val_w2_loss"]},
        indent=2))
    (OUT_DIR / "results.json").write_text(json.dumps(results, indent=2))
    return results


