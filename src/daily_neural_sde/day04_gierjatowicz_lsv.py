"""Day 4: Gierjatowicz et al. (2020) LSV neural SDE -> SINDy distillation.

Pipeline (all settings frozen in ``configs/daily_neural_sde_day04.json``):

1. Take the paper's local stochastic volatility (LSV) form (5.3) as a
   benchmark, cut to a Heston-type system in log-price coordinates
   x = log S and variance v:
   d x_t = (r - 0.5 v_t) dt + sqrt(v_t) dB^S_t,
   d v_t = kappa (theta - v_t) dt + xi sqrt(v_t) dB^V_t,
   d<B^S, B^V>_t = rho dt, with declared parameters
   (r, kappa, theta, xi, rho) = (0.02, 2.0, 0.04, 0.30, -0.70),
   S_0 = 1 (x_0 = 0), v_0 = 0.04. The paper's market calibration,
   hedging network and robust lookback bounds are NOT tested here
   (declared cuts; see the config): trajectories are regenerated by
   full-truncation Euler-Maruyama at dt = 0.001 and observed every
   0.05 on [0, 1] (21 points per trajectory).
2. Fit a generic MLP neural SDE in the paper's LSV spirit (one small
   network per field, softplus-positive Cholesky diffusion) with two
   Gaussian transition likelihoods (EM freezing f and Sigma at the
   interval start; substep with K = 8 internal steps re-evaluating
   Sigma at the running mean, drift-Jacobian covariance term omitted
   -- documented limitation). The distilled teacher is the substep
   estimator, fixed a priori per the Day 1 reflection. The
   discretization-bias diagnostic is split by variance regime
   (low / mid / high v at the transition start), because the bias
   channel here is the freezing of sqrt(v), whose curvature bites
   hardest at low v. The diffusion comparison carries a pre-declared
   tie zone of 0.01 in Sigma NRMSE (Day 3 reflection).
3. Distill the substep teacher into polynomial SINDy models in (x, v)
   by direct function queries on trajectory-disjoint splits, in the
   conventions of ``src/distill.py`` (validation-only selection,
   test once). The diffusion target is the Cholesky matrix L
   (entries L11, L12, L21, L22 with L12 = 0 fixed by the triangular
   identification, since the likelihood identifies Sigma = L L^T,
   not L itself). A collinearity diagnostic on train query states
   precedes fitting (Day 2 reflection); an off-manifold grid
   diagnostic is standard, with the v = 0.16 column reported
   separately as the extrapolation column (Day 3 reflection).
4. Validate by paired simulation with the full (non-diagonal)
   diffusion matrix and shared Brownian increments, retaining
   failed-trajectory mass and counting negative-variance excursions
   separately. Paper-axis proxy (H6): European call (K = 1, T = 1)
   and the paper's lookback payoff (max_t S_t - S_T) priced by Monte
   Carlo under teacher, symbolic and truth with COMMON random
   increments (Day 3 common-random-numbers lesson).

Run from the repository root:  ``python -m src.daily_neural_sde.day04_gierjatowicz_lsv``
Outputs land in ``outputs/daily_neural_sde/day04/``.
"""
